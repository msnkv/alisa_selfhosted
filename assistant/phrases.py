"""Короткие служебные фразы: отзыв на кодовую фразу и заглушки.

Это единственные слова, которые ассистент говорит не от модели, а от
себя, поэтому они собраны в одном месте: их синтезирует и голосовой
цикл на ПК, и сервер для спутника.

Почему их несколько, а не по одной. Одна и та же фраза, услышанная
двадцатый раз за вечер, перестаёт восприниматься как речь и начинает
раздражать — особенно «Секунду, смотрю», которая звучит на каждом
вопросе с поиском. Список лечит это бесплатно: синтез всё равно идёт
при прогреве, разница только в том, что фраз готовится не две, а
полтора десятка.

Три набора, и делятся они не по вкусу, а по честности:

- `ACK` — отзыв на кодовую фразу. Ничего не обещает.
- `THINKING` — пока ассистент думает. Про поиск тут ни слова, потому
  что в этот момент ещё неизвестно, будет ли он: половина вопросов
  отвечается из знаний модели за две секунды.
- `SEARCH` — когда инструмент уже вызван. Здесь «смотрю» и «ищу»
  говорить можно: это правда, поиск в эту секунду идёт.

Разделение не придирка. В промпте есть правило «никогда не говори, что
нашла, если не искала», и нарушать его собственными фразами было бы
смешно.

Требования к фразе: короткая (меньше секунды речи — она звучит перед
ответом и задерживает его), без цифр и значков, в манере ассистента.
"""

from __future__ import annotations

import random

# Самое первое: короткий кивок «угу», почти сразу. Он ничего не
# обещает и не занимает канал - четыре десятых секунды, - зато снимает
# главный вопрос слушателя из другой комнаты: «меня вообще услышали?».
# Полноценная заглушка на этом месте не годится (пробовали, см.
# CLAUDE.md), а кивок годится именно потому, что он короче ответа.
NOD_AFTER_S = 1.2

# Через сколько секунд молчания спутник подаёт голос. Он, в отличие от
# ПК, не знает, пошёл ли сервер в интернет - видит только, что ответа
# всё нет. Поэтому решает по времени.
#
# Четыре с половиной секунды выбраны не на глаз: ответ без поиска
# приходит к спутнику за две с половиной - три секунды (распознавание
# плюс модель плюс передача), а с поиском - от шести. То есть к этому
# моменту ожидание уже заведомо долгое. Пробовали говорить раньше, на
# полутора секундах: на быстром ответе «секунду, смотрю» звучало прямо
# перед самим ответом и выглядело глупо.
FILLER_AFTER_S = 4.5

# Как часто можно повторять заглушку. Вопрос с несколькими поисками
# занимает до тридцати секунд, и одной фразы в начале на это не хватает.
# Но и подряд их говорить нельзя - именно это звучало как каша.
FILLER_GAP_S = 8.0

# Отзыв: «я тебя услышала, говори». Из другого конца комнаты это
# единственный признак, что кодовая фраза сработала.
ACK_PHRASES = [
    "Да?",
    "Да, братик?",
    "Ммм?",
    "Слушаю.",
    "Я тут.",
    "Что такое?",
]

# Кивок: «я тебя услышала, работаю». Короче всего остального, поэтому
# звучит даже там, где ответ уже на подходе.
NOD_PHRASES = [
    "Угу.",
    "Ага.",
    "Хм.",
    "Так.",
    "Ммм.",
]

# Пока думает. Ни слова про поиск: он ещё может не понадобиться.
THINKING_PHRASES = [
    "Ммм, сейчас.",
    "Так, секундочку.",
    "Сейчас подумаю.",
    "Ага, минутку.",
    "Так-так.",
    "Эм, погоди чуток.",
]

# Инструмент уже вызван — значит поиск действительно идёт.
SEARCH_PHRASES = [
    "Секунду, смотрю.",
    "Так, ищу.",
    "Сейчас гляжу.",
    "Минутку, проверяю.",
    "Уже смотрю, братик.",
    "Так, где же это.",
    "Подождите, сэмпай.",
]

# Когда сервер ответил ошибкой. Спутник раньше писал это в консоль и
# молчал - а человек в другой комнате консоли не видит и ждёт зря.
ERROR_PHRASES = [
    "Ой, не получилось.",
    "Гомен, что-то сломалось.",
    "Ой, у Алисы-тян ошибка.",
]

# Имена наборов общие для сервера и спутника: сервер отдаёт их такими
# же ключами в JSON, см. `/phrases` в server.py.
POOLS = {
    "ack": ACK_PHRASES,
    "nod": NOD_PHRASES,
    "thinking": THINKING_PHRASES,
    "search": SEARCH_PHRASES,
    "error": ERROR_PHRASES,
}


class Pool:
    """Случайная фраза, но не та же, что в прошлый раз.

    Простой `random.choice` повторяется: на шести фразах вероятность
    услышать ту же самую подряд — одна шестая, а два повтора подряд
    сразу считываются как «заело». Поэтому прошлая фраза исключается из
    выбора, и подряд одно и то же не звучит никогда.
    """

    def __init__(self, items) -> None:
        self._items = list(items)
        self._last = -1

    def __len__(self) -> int:
        return len(self._items)

    def pick(self):
        """Следующая фраза или None, если набор пуст."""
        count = len(self._items)
        if count == 0:
            return None
        if count == 1:
            self._last = 0
        elif self._last < 0:
            self._last = random.randrange(count)
        else:
            index = random.randrange(count - 1)
            # Пропускаем прошлую: индексы за ней сдвигаются на один.
            self._last = index + 1 if index >= self._last else index
        return self._items[self._last]
