"""Системный промпт: правила ответа, мои файлы из data/ и текущее время."""

from __future__ import annotations

import logging
import re
from datetime import datetime
from pathlib import Path

log = logging.getLogger(__name__)

# Для даты нужен родительный падеж ("22 октября"), поэтому своя таблица:
# strftime на Windows с русской локалью ведёт себя непредсказуемо.
MONTHS_GENITIVE = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)
WEEKDAYS = (
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье",
)


def human_now(now: datetime | None = None) -> str:
    """Дата и время словами: 'среда, 22 октября 2026 года, 17:05'."""
    now = now or datetime.now()
    return (
        f"{WEEKDAYS[now.weekday()]}, {now.day} {MONTHS_GENITIVE[now.month - 1]} "
        f"{now.year} года, {now:%H:%M}"
    )


class Knowledge:
    """Файлы из data/, целиком загружаемые в промпт.

    RAG здесь не нужен: файлы маленькие, а у модели контекст на миллион
    токенов. Перед каждым запросом сверяем время изменения файлов, так что
    правки в data/ подхватываются без перезапуска ассистента.
    """

    def __init__(self, data_dir: Path) -> None:
        self.data_dir = data_dir
        self._fingerprint: tuple | None = None
        self._text = ""

    def files(self) -> list[Path]:
        if not self.data_dir.is_dir():
            return []
        # README в data/ - это инструкция для человека, а не знание про него.
        # Без этой строчки она уезжает в промпт и ассистент считает её
        # частью моих личных данных.
        return sorted(
            path
            for path in self.data_dir.glob("*.md")
            if path.stem.lower() != "readme"
        )

    def _current_fingerprint(self) -> tuple:
        return tuple((p.name, p.stat().st_mtime_ns) for p in self.files())

    def text(self) -> str:
        """Склеенное содержимое файлов. Перечитывает их при изменении."""
        fingerprint = self._current_fingerprint()
        if fingerprint != self._fingerprint:
            blocks = []
            for path in self.files():
                body = path.read_text(encoding="utf-8").strip()
                blocks.append(f"--- файл {path.name} ---\n{body}")
            self._text = "\n\n".join(blocks)
            self._fingerprint = fingerprint
            log.info(
                "данные перечитаны: файлов %d, символов %d",
                len(fingerprint), len(self._text),
            )
        return self._text


# Порядок блоков здесь важен для денег, а не для красоты: DeepSeek кэширует
# совпадающее начало промпта и берёт за него в пятьдесят раз меньше. Поэтому
# всё неизменное (правила и файлы из data/) идёт сначала, а текущее время —
# единственное, что меняется каждую минуту — в самом конце.
SYSTEM_TEMPLATE = """Ты {name} — голосовой помощник, работающий дома у {owner}.

Как отвечать:
- Твой ответ читает вслух синтезатор речи. Предел — {max_sentences} предложения и примерно {max_words} слов на весь ответ. Это предел, а не цель: обычно хватает одной-двух коротких фраз.
- Если полный ответ в этот бюджет не влезает, НЕ ужимай его в длинные предложения. Скажи одно самое важное и предложи уточнить: «рассказать по шагам?», «назвать остальное?». Например, на вопрос про рецепт правильный ответ — это главный приём или главная ошибка, а не весь рецепт целиком.
- Никакой разметки: без markdown, звёздочек, решёток, списков, нумерации и ссылок.
- В ответе не должно быть ни одной цифры и ни одного сокращения — только слова. Не «95,4 ₽», а «девяносто пять рублей сорок копеек». Не «25 км/ч», а «двадцать пять километров в час». Не «60–90 дней», а «от шестидесяти до девяноста дней». Не «т.е.», а «то есть». Диапазон читается как «от» и «до», а не как тире.
- Если в моих записях место или вещь обозначены кодом или сокращением, расшифруй его словами. Код вслух бесполезен: вместо «Л-Н-3» говори «левый стеллаж, секция у входа, третий уровень».
- Говори простыми фразами, без канцелярита и без вступлений вида «конечно» или «отличный вопрос».

Откуда брать ответ:
- Если спрашивают про личные дела, вещи, рецепты или записи {owner} — отвечай строго по файлам из раздела «Личные данные» ниже. Не додумывай то, чего там нет.
- Если в файлах этого нет, а вопрос про устойчивые факты — природа, техника, история, кулинария, как что устроено, сколько чего-то обычно бывает — отвечай из своих знаний. Отсутствие интернета тут не помеха: такие сведения не меняются, и отказываться от ответа нельзя.
{fresh_data_rule}
- Если ответа нет или ты не уверен — скажи об этом прямо одним предложением. Выдумывать факты, числа и цены нельзя ни при каких условиях.

Личные данные {owner}:
{knowledge}

Сейчас {now}.
"""

# Правило про свежие данные зависит от того, подключён ли уже веб-поиск.
# На шаге 1 инструментов нет, и честнее сказать об этом, чем врать по памяти.
FRESH_DATA_WITH_TOOLS = (
    "- Если нужны сведения, которые меняются со временем (курсы валют, погода, "
    "новости, цены, расписания, маршруты) — обязательно проверь их инструментами "
    "поиска. Отвечать по памяти в таких случаях запрещено."
)
FRESH_DATA_NO_TOOLS = (
    "- Отдельно про сведения, которые меняются день ко дню: курсы валют и "
    "криптовалют, погода, новости, цены и наличие товаров, расписания транспорта, "
    "время в пути. Их сейчас проверить нельзя, потому что доступа в интернет у "
    "тебя пока нет — так и скажи, не называя цифр по памяти. Это правило про "
    "меняющиеся данные и только про них: справочные факты оно не затрагивает."
)


def build_system_prompt(
    *,
    name: str,
    owner: str,
    max_sentences: int,
    max_words: int,
    knowledge: str,
    tools_available: bool = False,
    now: datetime | None = None,
) -> str:
    return SYSTEM_TEMPLATE.format(
        name=name,
        owner=owner,
        now=human_now(now),
        max_sentences=max_sentences,
        max_words=max_words,
        fresh_data_rule=(
            FRESH_DATA_WITH_TOOLS if tools_available else FRESH_DATA_NO_TOOLS
        ),
        knowledge=knowledge or "(файлов в data/ нет)",
    )


# Модель иногда всё равно выдаёт звёздочки или дефисы списка. Синтезатор речи
# читает их вслух как мусор, поэтому подчищаем перед озвучкой.
_MARKUP = re.compile(r"[*_`#]+")
_LIST_BULLET = re.compile(r"^\s*[-•–—]\s+", re.MULTILINE)


def clean_for_speech(text: str) -> str:
    text = _MARKUP.sub("", text)
    text = _LIST_BULLET.sub("", text)
    text = re.sub(r"\s*\n\s*", " ", text)
    return re.sub(r"\s{2,}", " ", text).strip()
