"""Системный промпт: правила ответа, мои файлы из data/ и текущее время."""

from __future__ import annotations

import logging
import re
from datetime import datetime
from pathlib import Path

log = logging.getLogger(__name__)

# Сказать «забудь» вслух — единственный способ сменить тему, не трогая
# клавиатуру. Список живёт здесь, в самом лёгком общем модуле, потому
# что нужен всем: и голосовому циклу, и текстовому режиму, и серверу.
# Раньше он был скопирован в трёх файлах, а сервер про него не знал
# вовсе — из-за этого «забудь» со спутника не срабатывало совсем:
# модель вежливо отвечала «забыла», а история оставалась на месте, и
# на следующий вопрос ассистент пересказывал всё, что «забыл».
FORGET_WORDS = ("забудь", "сброс", "новая тема")

# Ответ на «забудь». Отвечаем сами, не спрашивая модель: она на это
# тратит секунды и каждый раз формулирует по-своему.
FORGOTTEN_REPLY = "Забыла, слушаю заново."


# Переключатель длинного ответа. Обычно ответ короткий - это голос, и
# слушать лекцию из колонки невозможно. Но иногда нужен разбор целиком,
# и тогда его просят словами.
#
# Тонкость: «подробнее» сюда НЕ входит намеренно. Ассистент сам часто
# заканчивает фразой «рассказать подробнее?», и если считать это
# просьбой о длинном ответе, то каждое уточнение превратится в лекцию.
# Поэтому «подробно» с границей слова (оно не совпадёт с «подробнее»),
# а «как можно подробнее» - отдельной фразой, там намерение явное.
_DETAIL = re.compile(
    r"\b(?:раскрой|детальн\w*|развёрнут\w*|развернут\w*|подробно"
    r"|во всех подробностях|как можно подробнее|целиком|полностью"
    r"|длинно|не торопись|говори долго|долго говори)\b",
    re.IGNORECASE,
)


# Явные команды на источник ответа. Нужны для предсказуемости: иногда
# важно точно знать, откуда придёт ответ, а не доверять решению модели.
#
# Обычный режим при этом остаётся прежним — модель сама решает. Гейт
# «без команды в записи не смотреть» делает главный случай проекта
# («где лежат болгарки») неудобным, поэтому он есть, но выключен:
# data.only_on_request в config.yaml.
MODE_RECORDS = "records"
MODE_WEB = "web"

_RECORDS = re.compile(
    r"(?:в|по)\s+(?:моих|мои)\s+(?:записях|заметках|записи|заметки|файлах)"
    r"|как\s+(?:там\s+)?у\s+меня\s+(?:записано|написано)"
    r"|что\s+у\s+меня\s+записано"
    r"|посмотри\s+(?:у\s+меня|в\s+записях|в\s+заметках)"
    r"|по\s+моим\s+(?:записям|заметкам)",
    re.IGNORECASE,
)
_WEB = re.compile(
    r"поищи|погугли|найди\s+в\s+(?:интернете|сети)"
    r"|посмотри\s+в\s+(?:интернете|сети)"
    r"|в\s+интернете\s+(?:посмотри|поищи|найди)",
    re.IGNORECASE,
)


def answer_mode(text: str) -> str | None:
    """Попросили ли явно определённый источник ответа.

    Записи сильнее интернета: если в вопросе есть и то и другое, человек
    скорее всего хочет сверить со своими записями.
    """
    text = text or ""
    if _RECORDS.search(text):
        return MODE_RECORDS
    if _WEB.search(text):
        return MODE_WEB
    return None


# Режим разговора и сказок. Это не «подробно»: там справка, только
# длинная, а здесь ассистент перестаёт быть справочником. Поэтому
# отдельный переключатель, свой предел длины и — главное — никаких
# инструментов: в разговоре лазить в интернет незачем.
#
# Режим липкий: включается фразой и держится, пока не скажешь «хватит»
# или «забудь». Иначе пришлось бы повторять «давай поговорим» перед
# каждой репликой, а это уже не разговор.
_LONG_FORM_ON = re.compile(
    r"давай\s+(?:поговорим|пообщаемся|поболтаем)"
    r"|поговорим|поболтаем|пообщаемся"
    r"|расскажи\s+(?:сказку|историю|что-нибудь|байку)"
    r"|сочини\s+(?:сказку|историю)"
    r"|сказку\s+на\s+ночь",
    re.IGNORECASE,
)
_LONG_FORM_OFF = re.compile(
    r"\bхватит\b|\bзакончили\b|\bдоговорили\b"
    r"|обычный\s+режим|как\s+обычно\s+отвечай"
    r"|всё,?\s+спасибо|спасибо,?\s+всё",
    re.IGNORECASE,
)


def long_form_request(text: str) -> bool:
    """Просят поговорить или рассказать историю."""
    return bool(_LONG_FORM_ON.search(text or ""))


def long_form_cancel(text: str) -> bool:
    """Просят вернуться к обычным коротким ответам."""
    return bool(_LONG_FORM_OFF.search(text or ""))


def wants_detail(text: str) -> bool:
    """Просят длинный ответ, а не обычный короткий."""
    return bool(_DETAIL.search(text or ""))


def is_forget(text: str) -> bool:
    """Это команда «забудь», а не вопрос.

    По началу фразы, а не целиком: «забудь всё» и «забудь, что я
    спрашивал» — тоже команда. А вот «что я просил забыть» вопрос, и
    сбрасывать по нему нельзя.
    """
    cleaned = (text or "").strip().lower().rstrip(".!?…").strip()
    return cleaned.startswith(FORGET_WORDS)

# Для даты нужен родительный падеж ("22 октября"), поэтому своя таблица:
# strftime на Windows с русской локалью ведёт себя непредсказуемо.
MONTHS_GENITIVE = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)
WEEKDAYS = (
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье",
)


def human_now(now: datetime | None = None) -> str:
    """Дата и время словами: 'среда, 22 октября 2026 года, 17:05'."""
    now = now or datetime.now()
    return (
        f"{WEEKDAYS[now.weekday()]}, {now.day} {MONTHS_GENITIVE[now.month - 1]} "
        f"{now.year} года, {now:%H:%M}"
    )


class Knowledge:
    """Файлы из data/, целиком загружаемые в промпт.

    RAG здесь не нужен: файлы маленькие, а у модели контекст на миллион
    токенов. Перед каждым запросом сверяем время изменения файлов, так что
    правки в data/ подхватываются без перезапуска ассистента.
    """

    def __init__(self, data_dir: Path) -> None:
        self.data_dir = data_dir
        self._fingerprint: tuple | None = None
        self._text = ""

    def files(self) -> list[Path]:
        if not self.data_dir.is_dir():
            return []
        # README в data/ - это инструкция для человека, а не знание про него.
        # Без этой строчки она уезжает в промпт и ассистент считает её
        # частью моих личных данных.
        return sorted(
            path
            for path in self.data_dir.glob("*.md")
            if path.stem.lower() != "readme"
        )

    def _current_fingerprint(self) -> tuple:
        return tuple((p.name, p.stat().st_mtime_ns) for p in self.files())

    def text(self) -> str:
        """Склеенное содержимое файлов. Перечитывает их при изменении."""
        fingerprint = self._current_fingerprint()
        if fingerprint != self._fingerprint:
            blocks = []
            for path in self.files():
                body = path.read_text(encoding="utf-8").strip()
                blocks.append(f"--- файл {path.name} ---\n{body}")
            self._text = "\n\n".join(blocks)
            self._fingerprint = fingerprint
            log.info(
                "данные перечитаны: файлов %d, символов %d",
                len(fingerprint), len(self._text),
            )
        return self._text


# Порядок блоков здесь важен для денег, а не для красоты: DeepSeek кэширует
# совпадающее начало промпта и берёт за него в пятьдесят раз меньше. Поэтому
# всё неизменное (правила и файлы из data/) идёт сначала, а текущее время —
# единственное, что меняется каждую минуту — в самом конце.
SYSTEM_TEMPLATE = """Ты {name} — голосовой помощник, работающий дома у {owner}.{city_note}{persona_note}

Как отвечать:
- Твой ответ читает вслух синтезатор речи. Предел — {max_sentences} предложения и примерно {max_words} слов на весь ответ. Это предел, а не цель: обычно хватает одной-двух коротких фраз.
- Если полный ответ в этот бюджет не влезает, НЕ ужимай его в длинные предложения. Скажи одно самое важное и предложи уточнить: «рассказать по шагам?», «назвать остальное?». Например, на вопрос про рецепт правильный ответ — это главный приём или главная ошибка, а не весь рецепт целиком.
- Первое предложение — это ответ на заданный вопрос, а не подход к нему. Спросили «можно ли» — начни с «да» или «нет». Спросили «сколько» — с количества. Спросили «где» — с места. Спросили «чем отличается» — с отличия.
- Не пересказывай то, что человек и так знает. Если он сам сослался на свою запись или сам назвал условие, повторять это обратно не надо: он только что это сказал.
- Предложить уточнить можно ТОЛЬКО после того, как ответил по сути. Подменять ответ предложением рассказать нельзя, это и выглядит, и звучит глупо. Плохо: «В твоих записях рецепт на два килограмма с морковью и гнётом, про пекинскую там ничего. Рассказать, как именно?» — тут нет ответа вообще. Хорошо: «Да, можно, только соли меньше и держать меньше: пекинская мягче и просаливается быстрее. Назвать пропорции?»
- Никакой разметки: без markdown, звёздочек, решёток, списков, нумерации и ссылок.
- В ответе не должно быть ни одной цифры и ни одного сокращения — только слова. Не «95,4 ₽», а «девяносто пять рублей сорок копеек». Не «25 км/ч», а «двадцать пять километров в час». Не «60–90 дней», а «от шестидесяти до девяноста дней». Не «т.е.», а «то есть». Диапазон читается как «от» и «до», а не как тире.
- Если в моих записях место или вещь обозначены кодом или сокращением, расшифруй его словами. Код вслух бесполезен: вместо «Л-Н-3» говори «левый стеллаж, секция у входа, третий уровень».
- Говори простыми фразами, без канцелярита и без вступлений вида «конечно» или «отличный вопрос».
- Разговор идёт подряд. Если просят уточнить, продолжить или отвечают «да» на твоё предложение рассказать подробнее — речь о том же, о чём шла речь в предыдущих репликах, а не о новой теме. Не перескакивай на другой рецепт или другую вещь.

Откуда брать ответ:
- Если спрашивают про личные дела, вещи, рецепты или записи {owner} — отвечай строго по файлам из раздела «Личные данные» ниже. Не додумывай то, чего там нет.\n- Файл about — это сведения о самом {owner}: кто он, что у него есть, что он любит и не ест. Учитывай их всегда, даже когда вопрос не про них: от них зависит, что вообще стоит советовать. Но вслух не пересказывай — отвечай на заданный вопрос.
- Если в файлах этого нет, а вопрос про устойчивые факты — природа, техника, история, как что устроено, сколько чего-то обычно бывает — отвечай из своих знаний. Отсутствие интернета тут не помеха: такие сведения не меняются, и отказываться от ответа нельзя.
- Если спрашивают про рецепт, пропорции, состав или порядок действий, которого в записях нет — ОБЯЗАТЕЛЬНО вызови поиск и ответь по найденному. Не отказывайся, не спрашивай разрешения поискать и не отвечай по памяти. Форма вопроса не важна: «как я делаю борщ» при отсутствии борща в записях — это тоже повод искать, а не предлагать поискать. Плохо: «Борща в твоих записях нет. Поискать рецепт в интернете?» и «Борща нет, сейчас поищу, секундочку» — в обоих случаях человек остался без ответа. Хорошо: вызвать поиск и сказать «В твоих записях борща нет, а в интернете главный приём такой: свёклу тушат отдельно с кислотой».
- Никогда не говори, что ты что-то нашла, проверила или посмотрела, если ты не вызывала инструменты в этом самом ответе. Плохо (поиск НЕ вызывался): «Алиса-тян глянула в интернет: главное там — соус из желтков» и «В интернете главное — соус без сливок» — это выдумка, никуда ты не ходила. Хорошо: либо вызвать поиск и тогда сослаться на него, либо честно сказать «в твоих записях этого нет, а по общим правилам главное — соус из желтков».
- И никогда не обещай поискать. «Сейчас поищу», «секундочку, посмотрю», «сейчас уточню» вместо ответа — это не ответ, а отписка: человек останется ни с чем. Либо вызываешь поиск прямо в этом ответе, либо отвечаешь тем, что знаешь.
{fresh_data_rule}
- Выдумывать факты, числа и цены нельзя ни при каких условиях.

Откуда ответ — должно быть слышно из самой фразы, а не из отдельной оговорки.
- Начинай сразу с ответа. Отдельное предложение-пометка перед ответом запрещено: оно занимает время и звучит казённо.
- Если отвечаешь по записям {owner} — назови это внутри фразы. Плохо: «Это из твоих записей. На два килограмма капусты...». Хорошо: «В твоих записях — на два килограмма капусты...».
- Если отвечаешь по найденному в интернете — так же внутри фразы. Плохо: «Это не из твоих записей, а найдено в интернете. Борщ варят так...». Хорошо: «В интернете пишут: сначала...».
- Если отвечаешь из своих знаний про устойчивые факты — источник не называй вообще, это и так понятно. Плохо: «Это общие сведения, не из твоих записей. Перфоратор...». Хорошо: «Перфоратор бьёт вдоль оси...».

Когда ответить нечем:
- Не начинай с доклада о неудаче и не объясняй, что именно не сработало: слушателю всё равно, подвёл поиск или сайт.
- Если для ответа не хватает подробности — города, даты, названия — просто спроси её одной короткой фразой. Плохо: «Не получилось узнать: поиск ничего не вернул. Скажи город — попробую ещё раз». Хорошо: «Какой город?».
- Если такой подробности не хватает с самого начала, спроси её сразу, не вызывая поиск: искать наугад бесполезно, а секунды это съедает.
- Если ответа действительно нет — скажи это одной короткой фразой и всё.

Личные данные {owner}:
{knowledge}

Сейчас {now}.{mode_rule}{detail_rule}{story_rule}
"""

