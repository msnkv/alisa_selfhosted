# Правило длинного ответа приписывается в САМЫЙ КОНЕЦ промпта, после
# времени. Это важно для денег: DeepSeek кэширует совпадающее начало, и
# если вписать это правило выше - например поменять там предел в словах,
# - то двадцать четыре тысячи токенов данных перестанут кэшироваться на
# каждом подробном вопросе. В конце оно не стоит ничего.
DETAIL_RULE = (
    "\n\nНа этот вопрос просят ответить подробно. Предел в {max_sentences}"
    " предложения и {max_words} слов на него НЕ действует: рассказывай"
    " развёрнуто и по порядку, пока не скажешь всё важное, примерно до"
    " {detail_words} слов. Предлагать уточнить не надо — подробностей уже"
    " попросили. Всё остальное в силе: никакой разметки и списков, ни"
    " одной цифры, числа словами."
)


# Без имени владельца намеренно: «Город Дима» по-русски не говорят, а
# склонять имя в коде — лишняя морока.
CITY_NOTE = (
    "\nДомашний город — {city}. Если в вопросе про погоду, транспорт, цены"
    " или местные дела город не назван, имей в виду этот и не спрашивай."
    " Знание города избавляет от вопроса «какой город», но не от проверки:"
    " погоду, цены и расписания всё равно ищи поиском."
)


def build_system_prompt(
    *,
    name: str,
    owner: str,
    max_sentences: int,
    max_words: int,
    knowledge: str,
    tools_available: bool = False,
    now: datetime | None = None,
    city: str = "",
    detail_words: int = 0,
    mode: str | None = None,
    story_words: int = 0,
    persona: str = "",
) -> str:
    return SYSTEM_TEMPLATE.format(
        name=name,
        owner=owner,
        # Город стоит в шапке, то есть в неизменной части промпта: кэш
        # DeepSeek от него не рассыпается. Пустой город - строки нет.
        city_note=CITY_NOTE.format(city=city) if city else "",
        persona_note=(
            PERSONA_NOTE.format(persona=persona.strip()) if persona.strip() else ""
        ),
        mode_rule=MODE_RULES.get(mode, ""),
        story_rule=(
            STORY_RULE.format(
                max_sentences=max_sentences,
                max_words=max_words,
                story_words=story_words,
            )
            if story_words
            else ""
        ),
        detail_rule=(
            DETAIL_RULE.format(
                max_sentences=max_sentences,
                max_words=max_words,
                detail_words=detail_words,
            )
            if detail_words
            else ""
        ),
        now=human_now(now),
        max_sentences=max_sentences,
        max_words=max_words,
        fresh_data_rule=(
            FRESH_DATA_WITH_TOOLS if tools_available else FRESH_DATA_NO_TOOLS
        ),
        knowledge=knowledge or "(файлов в data/ нет)",
    )


# Модель иногда всё равно выдаёт звёздочки или дефисы списка. Синтезатор речи
# читает их вслух как мусор, поэтому подчищаем перед озвучкой.
_MARKUP = re.compile(r"[*_`#]+")
_LIST_BULLET = re.compile(r"^\s*[-•–—]\s+", re.MULTILINE)


# DeepSeek иногда пытается вызвать инструмент и на том шаге, где
# инструментов ему не дали. Вызов тогда приезжает не вызовом, а текстом
# в его служебной разметке — и без этой проверки уходит прямо в синтез.
# Слышно это было как бессвязный набор слов вместо ответа.
_TOOL_MARKUP = re.compile(r"DSML|invoke\s+name=|<\s*/?\s*(?:tool_call|function)\b")


def looks_like_tool_markup(text: str) -> bool:
    """Это не ответ, а попытка вызвать инструмент текстом."""
    return bool(_TOOL_MARKUP.search(text or ""))


def clean_for_speech(text: str) -> str:
    text = _MARKUP.sub("", text)
    text = _LIST_BULLET.sub("", text)
    text = re.sub(r"\s*\n\s*", " ", text)
    return re.sub(r"\s{2,}", " ", text).strip()
